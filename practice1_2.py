def bs2(arr, x): #возвращает позицию для вставки x в отсортированный массив
  lo = 0
  hi = len(arr)
  while lo < hi:
    m = lo + (hi - lo) // 2
    if arr[m] < x: #все элементы до середины включительно меньше x, ищем правее
      lo = m + 1
    else: #позиция вставки находится в середине или левее
      hi = m
  return lo


