def ps(arr):
  if len(arr) < 3: #если элементов меньше трёх, массив не может быть горным
    print("Массив не горный")
  lo = 0
  hi = len(arr) - 1
  while lo < hi:
    m = lo + (hi - lo) // 2
    if arr[m] < arr[m+1]: #если подъём продолжается, пик находится правее
      lo = m + 1
    else: #иначе пик уже слева или совпадает с серединой
      hi = m

  if lo == 0 or lo == len(arr) - 1: #пик не может быть на краю массива
    return "Массив не горный"

  for i in range(lo): #проверяем, что до пика строгое возрастание
    if arr[i] >= arr[i+1]:
      return "Массив не горный"

  for i in range(lo, len(arr)-1): #проверяем, что после пика строгое убывание
    if arr[i] <= arr[i+1]:
      return "Массив не горный"

  return lo #возвращаем индекс найденного пика

