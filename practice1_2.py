def neg(arr):
  cnt = 0 #счётчик отрицательных чисел
  lo = 0
  hi = len(arr) - 1
  while lo <= hi:
    m = lo + (hi - lo) // 2
    if arr[m] < 0: #если середина отрицательна, всё слева тоже отрицательно
      cnt = m + 1
      lo = m + 1
    else:
      hi = m - 1
  return cnt

def pos(arr):
  fst = -1 #индекс первого положительного элемента
  lo = 0
  hi = len(arr) - 1
  while lo <= hi:
    m = lo + (hi - lo) // 2
    if arr[m] > 0:
      hi = m - 1
      fst = m
    else:
      lo = m + 1
  if fst == -1:
    return 0
  return len(arr) - fst

